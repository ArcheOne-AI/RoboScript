"""Task Memory (docs/concepts/learning.md): the per-task document S1 writes, S2 refines and P3
reads frozen. A library usable without a model; the `memory` toolset wraps it for the S1 Demo
Reader and the Revisers.

- `doc`: `MemoryDoc` (INSTRUCTION, OBJECTS, WORKFLOW [stable]; LESSONS [dynamic]; NOTES; SCRATCH
  in caches) as `memory.md` + `params.json`; `view` for models (`detail=False`: the Actor's view,
  without provenance); `content_hash`.
- `params`: the typed parameter table: numbers, categories, GraspSpec / PlaceSpec specs
  (the specs themselves live in `roboscript.manipulation.specs`).
- `edits`: typed edit operations (`EditOp`), `EditCosts`, `apply` and the `Editor` (budget,
  revision limits, linter, records; a method's own checks as `EditValidator`s).
- `objects`: the OBJECTS section's role lines (`parse_objects`, `object_roles`).
- `linter`: `lint` (errors and warnings); vocabularies and limits come from the recipe.
- `cache`: `open_cache` (a cache for one S2 seed), `diff(M, C)` and `merge(M, C, alpha)` with
  provenance; a jitter when C == M.
- `store`: versions on disk (`FileMemoryStore`), freeze records, the store extension point.
- `manifest`: `MemoryManifest`, the frozen version of each task a benchmark's evaluation runs
  (`build_manifest`, `load_frozen`).
- `config`: `load_recipe` (e.g. `recipes/wicl/`) and `MemoryConfig`.
- `artifact`: a version as an artifact (`TaskMemory`, kind `task_memory`), `MemoryArtifacts`
  (the `roboscript.artifact_stores` entry), `memory_ref` and `manifest_stack`.

```python
recipe = load_recipe(Path("recipes/wicl"))
alpha, budget = 0.5, 2  # a method's step and budget for this seed (wicl: its schedule)
cache = open_cache(memory, budget=budget, seed=seed, rules=recipe.rules("s2"), lint=recipe.lint)
cache.edit({"op": "set_number", "param": "pre_grasp", "value": 0.12, "why": "stopped short"})
merged = merge(memory, cache.doc, alpha, seed=seed, attempt=2)
if merged.doc is not None:  # else a jitter
    version = await store.commit(merged.doc, status="merged", parent=memory.version, ...)
```
"""

